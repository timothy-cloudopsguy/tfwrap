# --- extract_app_name ------------------------------------------------------

@pytest.mark.parametrize('value,expected', [
    ('foo', 'foo'),
    ('yes', 'yes'),
    (123, '123'),
    (0, '0'),
    (None, ''),
    ('', ''),
])
def test_extract_app_name_ok(value, expected):
  assert extract_app_name({'app_name': value}, 'properties.dev.yaml') == expected


def test_extract_app_name_missing_key():
  assert extract_app_name({}, 'properties.dev.yaml') == ''


@pytest.mark.parametrize('value', [True, False])
def test_extract_app_name_rejects_bool(value):
  with pytest.raises(ValueError) as exc:
    extract_app_name({'app_name': value}, 'properties.dev.yaml')
  assert 'boolean' in str(exc.value)
  assert 'quote it' in str(exc.value)


@pytest.mark.parametrize('value', [1.5, 1.0])
def test_extract_app_name_rejects_float(value):
  with pytest.raises(ValueError) as exc:
    extract_app_name({'app_name': value}, 'properties.dev.yaml')
  assert 'decimal point' in str(exc.value)


@pytest.mark.parametrize('value', [['a'], {'a': 1}])
def test_extract_app_name_rejects_non_scalar(value):
  with pytest.raises(ValueError) as exc:
    extract_app_name({'app_name': value}, 'properties.dev.yaml')
  assert 'must be a string' in str(exc.value)


@pytest.mark.parametrize('raw', ['yes', 'on', 'no', 'off', 'true', 'false'])
def test_extract_app_name_rejects_yaml_booleans(raw):
  props = yaml.safe_load('app_name: {}\n'.format(raw))
  assert isinstance(props['app_name'], bool)
  with pytest.raises(ValueError):
    extract_app_name(props, 'properties.dev.yaml')


