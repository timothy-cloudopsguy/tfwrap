import json
import logging

import pytest
import yaml

from tfwrap.main import (
    PROPERTIES_EXTENSIONS,
    extract_app_name,
    find_properties_files,
    load_properties,
    warn_if_stale_bootstrap,
)

LEGACY_MAIN_TF = 'locals {\n  props = jsondecode(file("${path.module}/../properties.${var.environment}.json"))\n}\n'


def _write_stale_bootstrap(target, main_tf=LEGACY_MAIN_TF, marker=True):
  bootstrap = target / 'bootstrap'
  bootstrap.mkdir(exist_ok=True)
  if marker:
    (bootstrap / '.tfwrap-autogenerated').write_text('# auto-generated\n')
  (bootstrap / 'main.tf').write_text(main_tf)
  return bootstrap


# --- find_properties_files -------------------------------------------------

def test_find_single_json(tmp_path):
  (tmp_path / 'properties.dev.json').write_text('{}')
  assert find_properties_files('dev', str(tmp_path)) == [str(tmp_path / 'properties.dev.json')]


def test_find_single_yaml(tmp_path):
  (tmp_path / 'properties.dev.yaml').write_text('app_name: x\n')
  assert find_properties_files('dev', str(tmp_path)) == [str(tmp_path / 'properties.dev.yaml')]


def test_find_single_yml(tmp_path):
  (tmp_path / 'properties.dev.yml').write_text('app_name: x\n')
  assert find_properties_files('dev', str(tmp_path)) == [str(tmp_path / 'properties.dev.yml')]


def test_find_order_is_extension_order(tmp_path):
  for ext in PROPERTIES_EXTENSIONS:
    (tmp_path / 'properties.dev.{}'.format(ext)).write_text('{}')
  assert find_properties_files('dev', str(tmp_path)) == [
    str(tmp_path / 'properties.dev.{}'.format(ext)) for ext in PROPERTIES_EXTENSIONS
  ]


def test_find_none(tmp_path):
  assert find_properties_files('dev', str(tmp_path)) == []


def test_find_ignores_other_env(tmp_path):
  (tmp_path / 'properties.prod.json').write_text('{}')
  assert find_properties_files('dev', str(tmp_path)) == []


