def test_warn_if_stale_bootstrap_does_not_modify_files(tmp_path):
  bootstrap = _write_stale_bootstrap(tmp_path)
  main_before = (bootstrap / 'main.tf').read_text()
  marker_before = (bootstrap / '.tfwrap-autogenerated').read_text()
  props = tmp_path / 'properties.dev.yaml'
  props.write_text('app_name: x\n')
  props_before = props.read_text()

  warn_if_stale_bootstrap(str(tmp_path), str(props))

  assert (bootstrap / 'main.tf').read_text() == main_before
  assert (bootstrap / '.tfwrap-autogenerated').read_text() == marker_before
  assert props.read_text() == props_before


# --- create_bootstrap_directory -------------------------------------------

def test_create_bootstrap_renders_candidate_set_hcl(tmp_path, make_wrapper):
  wrapper = make_wrapper(target_dir=str(tmp_path))
  wrapper.create_bootstrap_directory()

  main_tf = (tmp_path / 'bootstrap' / 'main.tf').read_text()
  assert 'props_candidates' in main_tf
  assert 'fileexists(' in main_tf
  assert 'yamldecode(file(local.props_file))' in main_tf
  assert 'jsondecode(file(local.props_file))' in main_tf
  assert 'properties.${var.environment}.${ext}' in main_tf
  assert 'properties.${var.environment}.json' not in main_tf

  bootstrap = tmp_path / 'bootstrap'
  assert (bootstrap / '.tfwrap-autogenerated').is_file()
  assert (bootstrap / 'outputs.tf').is_file()
  assert (bootstrap / 'variables.tf').is_file()
  assert (bootstrap / 'versions.tf').is_file()


def test_create_bootstrap_leaves_existing_dir_untouched(tmp_path, make_wrapper):
  bootstrap = tmp_path / 'bootstrap'
  bootstrap.mkdir()
  (bootstrap / 'main.tf').write_text('ORIGINAL CONTENT\n')
  (bootstrap / '.tfwrap-autogenerated').write_text('# auto\n')

  wrapper = make_wrapper(target_dir=str(tmp_path))
  wrapper.create_bootstrap_directory()

  assert (bootstrap / 'main.tf').read_text() == 'ORIGINAL CONTENT\n'
  assert not (bootstrap / 'outputs.tf').exists()


def test_legacy_string_is_absent_after_generation(tmp_path, make_wrapper):
  wrapper = make_wrapper(target_dir=str(tmp_path))
  wrapper.create_bootstrap_directory()
  main_tf = (tmp_path / 'bootstrap' / 'main.tf').read_text()
  assert LEGACY_MAIN_TF not in main_tf
  assert warn_if_stale_bootstrap(str(tmp_path), str(tmp_path / 'properties.dev.yaml')) is None
