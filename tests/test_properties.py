# --- warn_if_stale_bootstrap ----------------------------------------------

def test_warn_if_stale_bootstrap_yaml(tmp_path, caplog):
  _write_stale_bootstrap(tmp_path)
  props = tmp_path / 'properties.dev.yaml'
  props.write_text('app_name: x\n')
  with caplog.at_level(logging.WARNING):
    warn_if_stale_bootstrap(str(tmp_path), str(props))
  assert 'clean step' in caplog.text
  assert '1.0.9' in caplog.text


